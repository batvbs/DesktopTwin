    /// <summary>
    /// 查内置中文原文。
    /// </summary>
    /// <param name="key">键。</param>
    /// <param name="text">原文。</param>
    public static bool TryGet(string key, out string text)
    {
        foreach (var entry in All)
        {
            if (string.Equals(entry.Key, key, System.StringComparison.OrdinalIgnoreCase))
            {
                text = entry.Value;
                return true;
            }
        }

        text = key;
        return false;
    }

